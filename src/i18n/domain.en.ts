/** Translate v1 message templates at display time, including historical logs. */
export function translateDomain(text: string, translate: (text: string) => string): string | undefined {
  let match: RegExpMatchArray | null;
  if ((match = text.match(/^情境 (\d+) 已开始。请先观察并收集证据。$/))) return `Scenario ${match[1]} started. Observe and collect evidence first.`;
  if ((match = text.match(/^再次观察：(.+)（该证据已记录，不重复计分）$/))) return `Observed again: ${translate(match[1])} (Already recorded; no duplicate points.)`;
  if ((match = text.match(/^已记录：(.+)$/))) return `Recorded: ${translate(match[1])}`;
  if ((match = text.match(/^当前(.+)；(可见持续补水|未见进水)。$/))) return `Water level: ${translate(match[1])}; ${translate(match[2])}.`;
  if ((match = text.match(/^(水位已到工作水位或更高|水位低于工作水位)，(进水组件仍在补水|进水组件当前没有水流)。$/))) return `${translate(match[1])}; ${translate(match[2])}.`;
  if ((match = text.match(/^已观察(.+)。本操作不增加诊断证据分。$/))) return `Observed: ${translate(match[1])}. This action does not add diagnosis evidence points.`;
  if ((match = text.match(/^(诊断正确。|诊断不正确。)(.+)$/))) return `${translate(match[1])} ${translate(match[2])}`;
  if ((match = text.match(/^拆卸被阻止，尚需：(.+)。$/))) return `Removal blocked. Still required: ${match[1].split('、').map(translate).join('; ')}.`;
  if ((match = text.match(/^存在 (\d+) 项关键安全错误，本次不能合格$/))) return `${match[1]} critical safety error${match[1] === '1' ? '' : 's'} recorded; this attempt cannot pass`;
  if ((match = text.match(/^复测未通过。(.+)请检查处理结果，再运行完整复测。$/))) return `Retest failed. ${translate(match[1])} Check the treatment, then run a complete retest.`;
  if ((match = text.match(/^复习处理流程中未完成的项目：(.+)。按本情境的适用流程操作，处理后确认组件完整装配。$/))) return `Review unfinished treatment steps: ${match[1].split('、').map(translate).join('; ')}. Follow this scenario’s applicable process and confirm full assembly after treatment.`;
  return undefined;
}
